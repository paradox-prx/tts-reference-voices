#!/usr/bin/env python3
"""Offline retry-policy evaluation from K takes per prompt (bench_tts.py --takes K), scored by score_run.py.
Writes retry_sim.json + retry_sim.md next to each scores.jsonl, or into --combine DIR for several runs together.

    eval/run.sh eval/score_run.py ../results/P5_rp110 --device cuda          # first: scores.jsonl
    eval/run.sh eval/retry_sim.py ../results/P5_rp110                         # then: the policy table
    eval/run.sh eval/retry_sim.py ../results/P5_rp1* --combine ../results/P5_summary --baseline rp105
    eval/run.sh eval/retry_sim.py ../results/P5_rp110 --labels human_labels.jsonl   # `bad` from human listening
    eval/run.sh eval/retry_sim.py --selftest                                  # synthetic sanity check

Takes need no seed: on vLLM-Omni 0.28 a seed does not reproduce a take, so the K takes of a prompt are K unseeded
requests (bench rows `take` 0..K-1). Grouping (takes.py): a setting is one bench run + the voice as the engine knows
it (--setting tag / params / dir to group otherwise); a prompt is the repo voice + prompt id / text, so settings
(e.g. repetition_penalty values, or trump-avg vs trump-prompt) pair by prompt.

Per take: gate_pass (the online verdict; score_run's gate_pass), bad (the outcome that matters; score_run's stricter
label, or a human label from --labels {"file": ..., "bad": true|false} where one exists), cost (seconds of audio
generated by default: failed loops are long; --cost latency for wall time) and the fallback rank the gateway uses when
every attempt fails (tts_gateway.quality.best: gate failures on text/SIM/audio before pace-band failures, then the
take whose pace is closest to expected).

Policies, each exact over the K takes of a prompt (no Monte-Carlo):
  retry R    try takes in order, stop at the first gate pass, after R+1 failures ship the best-ranked attempt;
             averaged over every ordered choice of R+1 of the K takes (K!/(K-R-1)! orders), so the order the takes
             were generated in does not matter. R = 0 is "no guardrail" (the first take, whatever it is).
  best-of-N  always generate N in parallel, ship the best-ranked gate-passing one (else the best-ranked); averaged
             over every N-subset of the K takes.
Reported per setting: final bad rate, mean attempts, extra compute vs R = 0, share of requests that still ship a
gate-failing take, with 95 % CIs from bootstrapping PROMPTS (takes of one prompt are correlated: failures cluster on
hard prompts, so f^(R+1) is shown only as the naive i.i.d. contrast), and the gate's recall / precision /
false-reject rate against `bad` (eval-tooling.md findings 27-29). Paired comparisons: every setting vs the baseline
on the prompts both have (difference in final bad rate at each R, bootstrap CI over the shared prompts).
"""
from __future__ import annotations

import argparse
import itertools
import json
import math
import random
import sys
from collections import defaultdict
from pathlib import Path
from statistics import mean

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from stats import bootstrap, rate  # noqa: E402
from takes import prompt_key, setting_key  # noqa: E402


def fallback_rank(t: dict) -> tuple:
    """Lower is better, as tts_gateway.quality.best(): 0 pass, 1 failed only QC checks, 2 outside the pace band;
    ties broken by |ln pace_ratio|."""
    pace_fail = any(r.startswith("pace") for r in t.get("gate_reasons", []))
    pr = t.get("pace_ratio")
    return (0 if t["gate_pass"] else 2 if pace_fail else 1, abs(math.log(pr)) if pr and pr > 0 else 0.0)


def eval_retry(takes: list[dict], R: int) -> dict:
    k = len(takes)
    m = min(R + 1, k)
    bad = att = cost = shipped_fail = 0.0
    n = 0
    for order in itertools.permutations(range(k), m):
        tried = []
        for i in order:
            tried.append(takes[i])
            if takes[i]["gate_pass"]:
                shipped = takes[i]
                break
        else:
            shipped = min(tried, key=fallback_rank)
        bad += shipped["bad"]
        shipped_fail += not shipped["gate_pass"]
        att += len(tried)
        cost += sum(t["cost"] for t in tried)
        n += 1
    return {"bad": bad / n, "attempts": att / n, "cost": cost / n, "shipped_gate_fail": shipped_fail / n,
            "cost_1": mean(t["cost"] for t in takes)}


def eval_best_of(takes: list[dict], N: int) -> dict:
    combos = list(itertools.combinations(takes, min(N, len(takes))))
    bad = sum(min(c, key=fallback_rank)["bad"] for c in combos) / len(combos)
    cost = sum(sum(t["cost"] for t in c) for c in combos) / len(combos)
    return {"bad": bad, "cost": cost, "cost_1": mean(t["cost"] for t in takes)}


def policy_table(prompts: dict[str, list[dict]], max_r: int, best_of: list[int], n_boot: int, seed: int) -> dict:
    keys = sorted(prompts)
    kmin = min(len(v) for v in prompts.values())
    takes = [t for v in prompts.values() for t in v]
    f = sum(t["bad"] for t in takes) / len(takes)
    rows = []
    for R in range(0, max_r + 1):
        if R + 1 > kmin:
            break
        per = {p: eval_retry(prompts[p], R) for p in keys}

        def bad_rate(ks, per=per):
            return mean(per[p]["bad"] for p in ks)

        def extra(ks, per=per):
            return sum(per[p]["cost"] for p in ks) / sum(per[p]["cost_1"] for p in ks) - 1

        rows.append({"R": R, "final_bad_rate": round(bad_rate(keys), 4),
                     "ci95": bootstrap(keys, bad_rate, n_boot, seed),
                     "mean_attempts": round(mean(per[p]["attempts"] for p in keys), 3),
                     "extra_compute": round(extra(keys), 4), "extra_compute_ci95": bootstrap(keys, extra, n_boot, seed),
                     "shipped_gate_fail": round(mean(per[p]["shipped_gate_fail"] for p in keys), 4),
                     "iid_prediction": round(f ** (R + 1), 4)})
    bo = []
    for N in best_of:
        if N > kmin:
            continue
        per = {p: eval_best_of(prompts[p], N) for p in keys}

        def bo_bad(ks, per=per):
            return mean(per[p]["bad"] for p in ks)

        extra_n = sum(per[p]["cost"] for p in keys) / sum(per[p]["cost_1"] for p in keys) - 1
        bo.append({"best_of": N, "final_bad_rate": round(bo_bad(keys), 4),
                   "ci95": bootstrap(keys, bo_bad, n_boot, seed), "extra_compute": round(extra_n, 4)})
    nbad = sum(t["bad"] for t in takes)
    nfail = sum(not t["gate_pass"] for t in takes)
    tp = sum(t["bad"] and not t["gate_pass"] for t in takes)
    fp = sum((not t["bad"]) and not t["gate_pass"] for t in takes)
    return {"n_prompts": len(keys), "takes_per_prompt": sorted({len(v) for v in prompts.values()}),
            "n_takes": len(takes), "take_bad": rate(nbad, len(takes)), "take_gate_fail": rate(nfail, len(takes)),
            "gate_recall": rate(tp, nbad), "gate_precision": rate(tp, nfail),
            "false_reject": rate(fp, len(takes) - nbad),
            "prompts_with_any_bad": sum(any(t["bad"] for t in v) for v in prompts.values()),
            "prompts_all_bad": sum(all(t["bad"] for t in v) for v in prompts.values()), "retry": rows, "best_of": bo}


def paired(settings: dict[str, dict[str, list[dict]]], baseline: str, max_r: int, n_boot: int, seed: int) -> list[dict]:
    """Every setting vs `baseline` on their shared prompts: difference in final bad rate after R retries."""
    base = settings[baseline]
    out = []
    for name, prompts in sorted(settings.items()):
        common = sorted(set(prompts) & set(base))
        if name == baseline or not common:
            continue
        kmin = min(min(len(prompts[p]), len(base[p])) for p in common)
        for R in range(0, min(max_r, kmin - 1) + 1):
            a = {p: eval_retry(base[p], R)["bad"] for p in common}
            b = {p: eval_retry(prompts[p], R)["bad"] for p in common}
            def diff(ks, a=a, b=b):
                return mean(b[p] - a[p] for p in ks)

            out.append({"baseline": baseline, "setting": name, "R": R, "n_prompts": len(common),
                        "bad_baseline": round(mean(a.values()), 4), "bad_setting": round(mean(b.values()), 4),
                        "diff": round(diff(common), 4), "diff_ci95": bootstrap(common, diff, n_boot, seed)})
    return out


def load_takes(files: list[Path], cost_key: str, labels: dict[str, bool],
               mode: str) -> dict[str, dict[str, list[dict]]]:
    """{setting: {prompt: [take, ...]}} from scores.jsonl files (see takes.py)."""
    out: dict[str, dict[str, list[dict]]] = defaultdict(lambda: defaultdict(list))
    for scores in files:
        with open(scores, encoding="utf-8") as f:
            for line in f:
                if not line.strip():
                    continue
                r = json.loads(line)
                cost = r.get(cost_key)
                if cost is None:
                    cost = r.get("audio_s") or r.get("duration_s") or 0.0
                out[setting_key(r, mode, default=scores.parent.name)][prompt_key(r)].append(
                    {"file": r["file"], "take": r.get("take", 0), "gate_pass": bool(r["gate_pass"]),
                     "gate_reasons": r.get("gate_reasons", []), "bad": bool(labels.get(r["file"], r["bad"])),
                     "cost": float(cost), "pace_ratio": r.get("pace_ratio"), "labelled": r["file"] in labels})
    return out


def fmt_ci(x: float, ci: tuple | list | None) -> str:
    return f"{x:.3f} [{ci[0]:.3f}, {ci[1]:.3f}]" if ci else f"{x:.3f}"


def markdown(result: dict) -> str:
    lines = [f"# Retry-policy simulation: {', '.join(result['scores'])}", "",
             f"Cost = `{result['cost']}`; bad = {result['bad_source']}; 95 % CIs bootstrap over prompts "
             f"({result['n_boot']} resamples). i.i.d. = f^(R+1), shown only for contrast. Takes are unseeded; "
             "settings pair by prompt.", ""]
    for run, t in result["settings"].items():
        lines += [f"## {run}", "",
                  f"{t['n_prompts']} prompts x {t['takes_per_prompt']} takes; take bad rate "
                  f"{fmt_ci(t['take_bad']['rate'], t['take_bad']['ci95'])}, gate fail rate "
                  f"{fmt_ci(t['take_gate_fail']['rate'], t['take_gate_fail']['ci95'])}; gate recall "
                  f"{t['gate_recall']['rate']}, precision {t['gate_precision']['rate']}, false-reject "
                  f"{t['false_reject']['rate']}; prompts with any bad take {t['prompts_with_any_bad']}, "
                  f"all takes bad {t['prompts_all_bad']}.", "",
                  "| policy | final bad rate [95% CI] | mean attempts | extra compute [95% CI] | ships gate-fail "
                  "| i.i.d. |",
                  "|---|---|---|---|---|---|"]
        for r in t["retry"]:
            lines.append(f"| retry R={r['R']} | {fmt_ci(r['final_bad_rate'], r['ci95'])} | {r['mean_attempts']:.2f} | "
                         f"{fmt_ci(r['extra_compute'], r['extra_compute_ci95'])} | {r['shipped_gate_fail']:.3f} | "
                         f"{r['iid_prediction']:.4f} |")
        for b in t["best_of"]:
            lines.append(f"| best-of-{b['best_of']} | {fmt_ci(b['final_bad_rate'], b['ci95'])} | {b['best_of']} | "
                         f"{b['extra_compute']:.3f} | - | - |")
        lines.append("")
    if result.get("paired"):
        lines += [f"## Paired by prompt vs `{result['baseline']}`", "",
                  "| setting | R | shared prompts | bad (baseline) | bad (setting) | difference [95% CI] |",
                  "|---|---|---|---|---|---|"]
        for p in result["paired"]:
            lines.append(f"| {p['setting']} | {p['R']} | {p['n_prompts']} | {p['bad_baseline']:.3f} | "
                         f"{p['bad_setting']:.3f} | {fmt_ci(p['diff'], p['diff_ci95'])} |")
        lines.append("")
    return "\n".join(lines)


def analyse(files: list[Path], args, labels: dict[str, bool]) -> dict:
    settings = load_takes(files, args.cost, labels, args.setting)
    best_of = [int(x) for x in args.best_of.split(",") if x]
    n_lab = sum(t["labelled"] for v in settings.values() for p in v.values() for t in p)
    result = {"scores": [str(f) for f in files], "cost": args.cost, "n_boot": args.boot, "setting_mode": args.setting,
              "bad_source": (f"human labels for {n_lab} takes, score_run's bad label for the rest" if labels
                             else "score_run's bad label"), "settings": {}}
    for name, prompts in sorted(settings.items()):
        if max(len(v) for v in prompts.values()) < 2:
            print(f"{name}: 1 take per prompt; retries need bench --takes K >= 2 (R = 0 only)")
        result["settings"][name] = policy_table(prompts, args.max_retries, best_of, args.boot, args.seed)
    if len(settings) > 1:
        names = sorted(settings)
        base = next((n for n in names if args.baseline and args.baseline in n), names[0])
        result["baseline"] = base
        result["paired"] = paired(settings, base, args.max_retries, args.boot, args.seed)
    return result


def selftest() -> None:
    """43 prompts x K=6; ~9 % bad takes concentrated on 4 hard prompts; gate recall ~0.85, 5 % false rejects."""
    rng = random.Random(1)
    prompts = defaultdict(list)
    for p in range(43):
        pf = 0.6 if p < 4 else 0.03
        for t in range(6):
            bad = rng.random() < pf
            gate_pass = (not bad and rng.random() > 0.05) or (bad and rng.random() < 0.15)
            prompts[f"p{p}"].append({"file": f"{p}_{t}", "take": t, "bad": bad, "gate_pass": gate_pass,
                                     "gate_reasons": [] if gate_pass else ["cer_nospace>0.15"],
                                     "cost": 95.0 if bad and rng.random() < 0.5 else 30.0,
                                     "pace_ratio": rng.uniform(0.8, 1.3)})
    t = policy_table(prompts, 3, [2, 3], 500, 0)
    print(json.dumps(t, indent=1))
    r = {x["R"]: x for x in t["retry"]}
    assert r[0]["mean_attempts"] == 1.0 and r[0]["extra_compute"] == 0.0
    assert r[3]["final_bad_rate"] <= r[1]["final_bad_rate"] <= r[0]["final_bad_rate"]
    assert r[3]["final_bad_rate"] > r[3]["iid_prediction"]          # clustered failures: i.i.d. is optimistic
    print("selftest ok")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("targets", nargs="*", help="run dirs with scores.jsonl, folders to search, or scores.jsonl files")
    ap.add_argument("--combine", help="analyse all targets together (paired across settings) and write here")
    ap.add_argument("--setting", choices=("run", "tag", "params", "dir"), default="run",
                    help="what makes a setting (always split by voice): bench run (default), tag, params, results dir")
    ap.add_argument("--baseline", help="setting the others are paired against (substring; default: first by name)")
    ap.add_argument("--max-retries", type=int, default=3)
    ap.add_argument("--best-of", default="2,3")
    ap.add_argument("--cost", default="audio_s", help="per-take cost field: audio_s (default) | latency | out_tokens")
    ap.add_argument("--labels", help='JSONL {"file", "bad"}: human labels replacing the automatic bad label')
    ap.add_argument("--boot", type=int, default=2000)
    ap.add_argument("--seed", type=int, default=0, help="bootstrap RNG seed (not a TTS seed)")
    ap.add_argument("--selftest", action="store_true")
    args = ap.parse_args()
    if args.selftest:
        selftest()
        return 0
    if not args.targets:
        ap.error("give scored run dirs (or --selftest)")
    files: list[Path] = []
    for t in args.targets:
        p = Path(t)
        if p.is_file():
            files.append(p)
        else:
            files += [p / "scores.jsonl"] if (p / "scores.jsonl").exists() else sorted(p.rglob("scores.jsonl"))
    if not files:
        raise SystemExit("retry_sim: no scores.jsonl found (run score_run.py first)")
    labels = {}
    if args.labels:
        with open(args.labels, encoding="utf-8") as f:
            labels = {r["file"]: bool(r["bad"]) for r in map(json.loads, filter(str.strip, f))}
    groups = [(files, Path(args.combine))] if args.combine else [([f], f.parent) for f in files]
    for group, out_dir in groups:
        result = analyse(group, args, labels)
        out_dir.mkdir(parents=True, exist_ok=True)
        out = out_dir / "retry_sim.json"
        out.write_text(json.dumps(result, indent=1) + "\n", encoding="utf-8")
        out.with_suffix(".md").write_text(markdown(result) + "\n", encoding="utf-8")
        print(markdown(result))
        print(f"-> {out}, {out.with_suffix('.md')}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
